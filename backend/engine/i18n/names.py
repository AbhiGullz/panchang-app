NAME_TABLES = {
    "tithi": TITHI_NAMES,
    "nakshatra": NAKSHATRA_NAMES,
    "yoga": YOGA_NAMES,
    "karana": KARANA_NAMES,
    "rashi": RASHI_NAMES,
}


def _ensure_lang(lang: str) -> str:
    if lang not in LANGUAGES:
        raise ValueError(f"Unsupported language: {lang}")
    return lang


def get_term_name(term_type: Literal["tithi", "nakshatra", "yoga", "karana", "rashi"], index: int, lang: str) -> str:
    _ensure_lang(lang)
    if term_type not in NAME_TABLES:
        raise ValueError(f"Unsupported term type: {term_type}")
    values = NAME_TABLES[term_type][lang]
    if index < 1 or index > len(values):
        raise ValueError(f"Index out of range for {term_type}: {index}")
    return values[index - 1]


def get_all_names(term_type: Literal["tithi", "nakshatra", "yoga", "karana", "rashi"], lang: str) -> list[str]:
    _ensure_lang(lang)
    if term_type not in NAME_TABLES:
        raise ValueError(f"Unsupported term type: {term_type}")
    return list(NAME_TABLES[term_type][lang])


def get_name_map(term_type: Literal["tithi", "nakshatra", "yoga", "karana", "rashi"], index: int) -> dict[str, str]:
    return {lang: get_term_name(term_type, index, lang) for lang in LANGUAGES}


def get_month_name(school: str, index: int, lang: str) -> str:
    _ensure_lang(lang)
    if school not in MONTH_NAMES:
        raise ValueError(f"Unsupported month school: {school}")
    values = MONTH_NAMES[school][lang]
    if index < 1 or index > len(values):
        raise ValueError(f"Month index out of range for {school}: {index}")
    return values[index - 1]


def get_month_name_map(school: str, index: int) -> dict[str, str]:
    return {lang: get_month_name(school, index, lang) for lang in LANGUAGES}


def get_lang_names(payload: dict, lang: str) -> dict[str, str | None]:
    _ensure_lang(lang)
    result: dict[str, str | None] = {}
    for field in ["tithi", "nakshatra", "yoga", "karana"]:
        value = payload.get(field)
        result[field] = value["name"][lang] if isinstance(value, dict) and isinstance(value.get("name"), dict) else None
    result["moon_sign"] = payload["moon_sign"][lang] if isinstance(payload.get("moon_sign"), dict) else None
    result["month_name"] = payload["month_name"][lang] if isinstance(payload.get("month_name"), dict) else None
    return result
